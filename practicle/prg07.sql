CREATE OR REPLACE TRIGGER trg_emp_insert_audit
AFTER INSERT ON employees
FOR EACH ROW
BEGIN
INSERT INTO emp_audit (
employee_id, emp_name, department_id, salary, action_date
) VALUES (
:NEW.employee_id,
:NEW.first_name || ' ' || :NEW.last_name,
:NEW.department_id,
:NEW.salary,
SYSTIMESTAMP
);
END;
/


