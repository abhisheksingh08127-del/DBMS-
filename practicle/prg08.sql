CREATE OR REPLACE TRIGGER trg_salary_update_audit
AFTER UPDATE OF salary ON employees
FOR EACH ROW
WHEN (OLD.salary != NEW.salary OR (OLD.salary IS NULL AND NEW.salary IS NOT NULL))
BEGIN
INSERT INTO salary_audit (
employee_id, old_salary, new_salary, updated_at
) VALUES (
:OLD.employee_id,
:OLD.salary,
:NEW.salary,
SYSTIMESTAMP
);
END;
/


