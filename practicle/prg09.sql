CREATE OR REPLACE TRIGGER trg_emp_delete_audit
AFTER DELETE ON employees
FOR EACH ROW
BEGIN
INSERT INTO deleted_emp_audit (
employee_id, emp_name, department_id, last_salary, deleted_by, deleted_at
) VALUES (
:OLD.employee_id,
:OLD.first_name || ' ' || :OLD.last_name,
:OLD.department_id,
:OLD.salary,
USER,
SYSTIMESTAMP
);
END;
/


